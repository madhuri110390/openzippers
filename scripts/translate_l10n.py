def translate_arb(lang_code, content):
    """
    Apply overrides for a specific language if available.
    """
    if lang_code not in TRANSLATIONS:
        # If we don't have a dictionary, we return the english content (which is what we have)
        # In a real tool, this would call Google Translate API.
        return content

    overrides = TRANSLATIONS[lang_code]
    for key, val in overrides.items():
        if key in content:
            content[key] = val
    
    return content

def main():
    print(f"Reading source: {SOURCE_FILE}")
    with open(SOURCE_FILE, 'r', encoding='utf-8') as f:
        source_data = json.load(f)

    # Process all ARB files in the directory
    for filename in os.listdir(L10N_DIR):
        if not filename.endswith('.arb') or filename == 'app_en.arb' or filename == 'app_es.arb':
            # Skip English source and Spanish (which we manually fixed already)
            continue
        
        lang_code = filename.replace('app_', '').replace('.arb', '')
        # Handle cases like zh_Hant
        if '_' in lang_code:
            lang_code_parts = lang_code.split('_')
            base_lang = lang_code_parts[0]
             # Fallback to base lang if specific not found (e.g. use zh for zh_Hant for now if not distinct)
             # Ideally we treat them differently, but for this mock simulation:
            if base_lang in TRANSLATIONS and lang_code not in TRANSLATIONS:
                 lang_code = base_lang
        
        print(f"Processing {filename} ({lang_code})...")
        
        file_path = os.path.join(L10N_DIR, filename)
        
        # We start with a COPY of the source data structure to ensure all keys exist
        # This prevents "missing key" errors
        new_content = source_data.copy()
        
        # Now apply translations
        new_content = translate_arb(lang_code, new_content)
        
        # Write back
        with open(file_path, 'w', encoding='utf-8') as f:
            json.dump(new_content, f, indent=2, ensure_ascii=False)
            
    print("Localization update complete.")

if __name__ == '__main__':
    main()
